/* ---------------------------------------------------------------------
   6. Valeurs calculées (requêtes utilisées par l'API)
   --------------------------------------------------------------------- */
-- Date de retour prévue et jours de retard (US-LOAN-01 / 02 / 03)
SELECT id_emprunt,
       date_emprunt + 14 AS date_retour_prevue,
       GREATEST(COALESCE(date_retour_effective, CURRENT_DATE) - (date_emprunt + 14), 0) AS jours_retard
  FROM emprunt ORDER BY id_emprunt;

-- Rang dans la file d'attente (US-RESA-01 / 02)
SELECT id_reservation, id_utilisateur, id_livre,
       ROW_NUMBER() OVER (PARTITION BY id_livre ORDER BY date_reservation, id_reservation) AS rang
  FROM reservation WHERE statut = 'WAITING' ORDER BY id_livre, rang;

-- Note moyenne et nombre d'avis (US-BOOK-02 / US-RATE-01)
SELECT l.id_livre, l.titre, ROUND(AVG(n.note), 1) AS note_moyenne, COUNT(n.note) AS nb_avis
  FROM livre l LEFT JOIN noter n ON n.id_livre = l.id_livre
 GROUP BY l.id_livre ORDER BY l.id_livre;
