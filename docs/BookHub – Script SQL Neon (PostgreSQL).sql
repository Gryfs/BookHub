/* =====================================================================
   BookHub - Modèle Physique de Données (MPD)
   SGBD      : Neon (PostgreSQL 16+ serverless)
   Nommage   : identique au MCD (Merise)
   Principe  : seules les données utiles sont stockées ; les valeurs
               calculables (date de retour prévue, retard, rang dans la
               file, note moyenne) sont obtenues par requête (section 6).
   Exécution : Neon Console > SQL Editor (coller le script), ou
               psql "postgresql://<user>:<pwd>@<host>/bookhub?sslmode=require" -f bookhub_schema_neon.sql
   Spring    : spring.datasource.url=jdbc:postgresql://<host>/bookhub?sslmode=require
   ===================================================================== */

SET TIME ZONE 'Europe/Paris';            -- Neon est en UTC par défaut

/* pg_trgm : index trigrammes -> recherche ILIKE '%...%' rapide (US-BOOK-03) */
CREATE EXTENSION IF NOT EXISTS pg_trgm;

/* Nettoyage (ré-exécution du script) */
DROP TABLE IF EXISTS noter, reservation, emprunt, livre, categorie, utilisateur CASCADE;
DROP FUNCTION IF EXISTS trg_emprunt_stock(), trg_emprunt_retour(), trg_livre_exemplaires(),
                        fn_marquer_retards(), fn_stats_bibliotheque(),
                        fn_top_livres(INT, INT), fn_emprunts_par_mois(INT),
                        fn_anonymiser_utilisateur(BIGINT);

/* ---------------------------------------------------------------------
   1. Tables
   --------------------------------------------------------------------- */
CREATE TABLE utilisateur (
    id_utilisateur     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    email              VARCHAR(255) NOT NULL,
    mot_de_passe_hash  VARCHAR(100) NOT NULL,            -- BCrypt coût 12 (60 car.)
    prenom             VARCHAR(100) NOT NULL,
    nom                VARCHAR(100) NOT NULL,
    telephone          VARCHAR(20)  NULL,
    pseudonyme         VARCHAR(50)  NULL,
    role               VARCHAR(20)  NOT NULL DEFAULT 'USER',
    CONSTRAINT pk_utilisateur PRIMARY KEY (id_utilisateur),
    CONSTRAINT ck_utilisateur_role CHECK (role IN ('USER', 'LIBRARIAN', 'ADMIN'))
);
/* E-mail unique sans tenir compte de la casse */
CREATE UNIQUE INDEX ux_utilisateur_email ON utilisateur (lower(email));

CREATE TABLE categorie (
    id_categorie  INT GENERATED BY DEFAULT AS IDENTITY,
    libelle       VARCHAR(100) NOT NULL,
    CONSTRAINT pk_categorie PRIMARY KEY (id_categorie),
    CONSTRAINT uq_categorie_libelle UNIQUE (libelle)
);

CREATE TABLE livre (
    id_livre                    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    isbn                        VARCHAR(17)   NOT NULL,  -- ISBN-13 avec tirets
    titre                       VARCHAR(255)  NOT NULL,
    auteur                      VARCHAR(255)  NOT NULL,
    description                 VARCHAR(2000) NULL,
    url_couverture              VARCHAR(500)  NULL,
    annee_publication           SMALLINT      NULL,
    nb_exemplaires_total        INT           NOT NULL DEFAULT 1,
    nb_exemplaires_disponibles  INT           NOT NULL,  -- maintenu par triggers
    id_categorie                INT           NOT NULL,  -- APPARTENIR (1,1)
    CONSTRAINT pk_livre PRIMARY KEY (id_livre),
    CONSTRAINT uq_livre_isbn UNIQUE (isbn),
    CONSTRAINT fk_livre_categorie FOREIGN KEY (id_categorie) REFERENCES categorie (id_categorie),
    CONSTRAINT ck_livre_exemplaires CHECK (nb_exemplaires_total >= 0
                                       AND nb_exemplaires_disponibles BETWEEN 0 AND nb_exemplaires_total),
    CONSTRAINT ck_livre_annee CHECK (annee_publication IS NULL OR annee_publication BETWEEN 1450 AND 2100)
);

/* Date de retour prévue = date_emprunt + 14 jours (RG-LOAN-02) : calculée, non stockée */
CREATE TABLE emprunt (
    id_emprunt             BIGINT GENERATED BY DEFAULT AS IDENTITY,
    date_emprunt           DATE        NOT NULL DEFAULT CURRENT_DATE,
    date_retour_effective  DATE        NULL,
    statut                 VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    id_utilisateur         BIGINT      NOT NULL,         -- EFFECTUER (1,1)
    id_livre               BIGINT      NOT NULL,         -- CONCERNER (1,1)
    CONSTRAINT pk_emprunt PRIMARY KEY (id_emprunt),
    CONSTRAINT fk_emprunt_utilisateur FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur),
    CONSTRAINT fk_emprunt_livre FOREIGN KEY (id_livre) REFERENCES livre (id_livre),
    CONSTRAINT ck_emprunt_statut CHECK (statut IN ('ACTIVE', 'LATE', 'RETURNED')),
    CONSTRAINT ck_emprunt_dates CHECK (date_retour_effective IS NULL OR date_retour_effective >= date_emprunt),
    CONSTRAINT ck_emprunt_rendu CHECK ((statut = 'RETURNED' AND date_retour_effective IS NOT NULL)
                                    OR (statut <> 'RETURNED' AND date_retour_effective IS NULL))
);

/* Rang dans la file = ordre des date_reservation en attente : calculé, non stocké */
CREATE TABLE reservation (
    id_reservation    BIGINT GENERATED BY DEFAULT AS IDENTITY,
    date_reservation  TIMESTAMPTZ NOT NULL DEFAULT now(),
    statut            VARCHAR(10) NOT NULL DEFAULT 'WAITING',
    id_utilisateur    BIGINT      NOT NULL,              -- FAIRE (1,1)
    id_livre          BIGINT      NOT NULL,              -- PORTER SUR (1,1)
    CONSTRAINT pk_reservation PRIMARY KEY (id_reservation),
    CONSTRAINT fk_reservation_utilisateur FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur),
    CONSTRAINT fk_reservation_livre FOREIGN KEY (id_livre) REFERENCES livre (id_livre),
    CONSTRAINT ck_reservation_statut CHECK (statut IN ('WAITING', 'AVAILABLE', 'CANCELLED'))   -- Attente / Dispo / Annulée
);

/* Association NOTER (0,n - 0,n) : identifiant technique id_noter pour
   respecter les URL du CDC (PUT/DELETE /api/ratings/{id}) ;
   la contrainte UNIQUE garantit un seul avis par lecteur et par livre */
CREATE TABLE noter (
    id_noter        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    id_utilisateur  BIGINT        NOT NULL,
    id_livre        BIGINT        NOT NULL,
    note            SMALLINT      NOT NULL,
    commentaire     VARCHAR(1000) NULL,
    CONSTRAINT pk_noter PRIMARY KEY (id_noter),
    CONSTRAINT uq_noter_utilisateur_livre UNIQUE (id_utilisateur, id_livre),
    CONSTRAINT fk_noter_utilisateur FOREIGN KEY (id_utilisateur) REFERENCES utilisateur (id_utilisateur),
    CONSTRAINT fk_noter_livre FOREIGN KEY (id_livre) REFERENCES livre (id_livre),
    CONSTRAINT ck_noter_note CHECK (note BETWEEN 1 AND 5)
);

/* ---------------------------------------------------------------------
   2. Index
   --------------------------------------------------------------------- */
CREATE INDEX ix_livre_titre_trgm   ON livre USING gin (titre gin_trgm_ops);
CREATE INDEX ix_livre_auteur_trgm  ON livre USING gin (auteur gin_trgm_ops);
CREATE INDEX ix_livre_categorie    ON livre (id_categorie);
CREATE INDEX ix_emprunt_utilisateur_statut ON emprunt (id_utilisateur, statut);
CREATE INDEX ix_emprunt_livre              ON emprunt (id_livre);
CREATE INDEX ix_reservation_livre_statut   ON reservation (id_livre, statut, date_reservation);
CREATE INDEX ix_reservation_utilisateur    ON reservation (id_utilisateur, statut);
CREATE INDEX ix_noter_livre                ON noter (id_livre);
/* Une seule réservation active par lecteur et par livre */
CREATE UNIQUE INDEX ux_reservation_active
    ON reservation (id_utilisateur, id_livre)
    WHERE statut IN ('WAITING', 'AVAILABLE');

/* ---------------------------------------------------------------------
   3. Triggers (PL/pgSQL) - stock d'exemplaires
   --------------------------------------------------------------------- */

/* T1 - Emprunt créé : décrémente les exemplaires disponibles (US-LOAN-01).
   Plus d'exemplaire -> ck_livre_exemplaires rejette l'emprunt. */
CREATE FUNCTION trg_emprunt_stock() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE livre SET nb_exemplaires_disponibles = nb_exemplaires_disponibles - 1
     WHERE id_livre = NEW.id_livre;
    RETURN NULL;
END $$;
CREATE TRIGGER emprunt_ai_stock AFTER INSERT ON emprunt
    FOR EACH ROW WHEN (NEW.statut <> 'RETURNED') EXECUTE FUNCTION trg_emprunt_stock();

/* T2 - Retour enregistré : ré-incrémente les exemplaires disponibles (US-LOAN-03). */
CREATE FUNCTION trg_emprunt_retour() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE livre SET nb_exemplaires_disponibles = nb_exemplaires_disponibles + 1
     WHERE id_livre = NEW.id_livre;
    RETURN NULL;
END $$;
CREATE TRIGGER emprunt_au_retour AFTER UPDATE OF statut ON emprunt
    FOR EACH ROW WHEN (OLD.statut <> 'RETURNED' AND NEW.statut = 'RETURNED')
    EXECUTE FUNCTION trg_emprunt_retour();

/* T3 - Le bibliothécaire modifie le nombre total d'exemplaires (US-BOOK-04) :
   l'écart est reporté sur les exemplaires disponibles. */
CREATE FUNCTION trg_livre_exemplaires() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.nb_exemplaires_total < OLD.nb_exemplaires_total - OLD.nb_exemplaires_disponibles THEN
        RAISE EXCEPTION 'Le nombre d''exemplaires ne peut pas être inférieur au nombre d''exemplaires empruntés.';
    END IF;
    NEW.nb_exemplaires_disponibles := OLD.nb_exemplaires_disponibles
                                    + (NEW.nb_exemplaires_total - OLD.nb_exemplaires_total);
    RETURN NEW;
END $$;
CREATE TRIGGER livre_bu_exemplaires BEFORE UPDATE OF nb_exemplaires_total ON livre
    FOR EACH ROW WHEN (NEW.nb_exemplaires_total IS DISTINCT FROM OLD.nb_exemplaires_total)
    EXECUTE FUNCTION trg_livre_exemplaires();

/* ---------------------------------------------------------------------
   4. Fonctions (procédures stockées)
   --------------------------------------------------------------------- */

/* F1 - Détection des retards (bloque l'emprunt : RG-LOAN-03).
   Retard = non rendu après date_emprunt + 14 jours.
   Appel quotidien par un @Scheduled Spring : SELECT fn_marquer_retards(); */
CREATE FUNCTION fn_marquer_retards() RETURNS INT LANGUAGE plpgsql AS $$
DECLARE n INT;
BEGIN
    UPDATE emprunt SET statut = 'LATE'
     WHERE statut = 'ACTIVE' AND date_emprunt + 14 < CURRENT_DATE;
    GET DIAGNOSTICS n = ROW_COUNT;
    RETURN n;
END $$;

/* F2 - Indicateurs du dashboard bibliothécaire / admin (US-DASH-02/03). */
CREATE FUNCTION fn_stats_bibliotheque()
RETURNS TABLE (nb_livres BIGINT, nb_exemplaires BIGINT, emprunts_actifs BIGINT,
               emprunts_en_retard BIGINT, reservations_en_attente BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT (SELECT COUNT(*) FROM livre),
           (SELECT COALESCE(SUM(l.nb_exemplaires_total), 0) FROM livre l),
           (SELECT COUNT(*) FROM emprunt WHERE statut IN ('ACTIVE', 'LATE')),
           (SELECT COUNT(*) FROM emprunt WHERE statut = 'LATE'),
           (SELECT COUNT(*) FROM reservation WHERE statut = 'WAITING');
$$;

/* F3 - Top N des livres les plus empruntés (défaut : 10 sur 12 mois). */
CREATE FUNCTION fn_top_livres(p_top INT DEFAULT 10, p_mois INT DEFAULT 12)
RETURNS TABLE (id_livre BIGINT, titre VARCHAR, auteur VARCHAR, nb_emprunts BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT l.id_livre, l.titre, l.auteur, COUNT(e.id_emprunt)
      FROM livre l
      JOIN emprunt e ON e.id_livre = l.id_livre
     WHERE e.date_emprunt >= CURRENT_DATE - make_interval(months => p_mois)
     GROUP BY l.id_livre
     ORDER BY COUNT(e.id_emprunt) DESC, l.titre
     LIMIT p_top;
$$;

/* F4 - Évolution mensuelle des emprunts (graphique du dashboard). */
CREATE FUNCTION fn_emprunts_par_mois(p_mois INT DEFAULT 12)
RETURNS TABLE (mois DATE, nb_emprunts BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT date_trunc('month', date_emprunt)::date, COUNT(*)
      FROM emprunt
     WHERE date_emprunt >= date_trunc('month', CURRENT_DATE) - make_interval(months => p_mois - 1)
     GROUP BY 1 ORDER BY 1;
$$;

/* F5 - Droit à l'oubli (US-AUTH-03 / RGPD).
   Les emprunts sont conservés (statistiques) mais rattachés à un compte
   anonymisé ; les avis et réservations sont supprimés. */
CREATE FUNCTION fn_anonymiser_utilisateur(p_id_utilisateur BIGINT) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM emprunt
                WHERE id_utilisateur = p_id_utilisateur AND statut IN ('ACTIVE', 'LATE')) THEN
        RAISE EXCEPTION 'Suppression impossible : des emprunts sont en cours.';
    END IF;

    DELETE FROM reservation WHERE id_utilisateur = p_id_utilisateur;
    DELETE FROM noter       WHERE id_utilisateur = p_id_utilisateur;

    UPDATE utilisateur
       SET email             = 'deleted-' || id_utilisateur || '@anonymized.invalid',
           mot_de_passe_hash = '!',                          -- aucun hash BCrypt valide
           prenom            = 'Utilisateur',
           nom               = 'supprimé',
           telephone         = NULL,
           pseudonyme        = NULL
     WHERE id_utilisateur = p_id_utilisateur;
END $$;

