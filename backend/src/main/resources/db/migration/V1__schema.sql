/* F1 - Détection des retards (bloque l'emprunt : RG-LOAN-03).
   Retard = non rendu après date_emprunt + 14 jours.
   Appel quotidien par un @Scheduled Spring : SELECT fn_marquer_retards(); */
CREATE FUNCTION fn_marquer_retards() RETURNS INT LANGUAGE plpgsql AS $$
DECLARE n INT;
BEGIN
    UPDATE emprunt SET statut = 'LATE'
     WHERE statut = 'ACTIVE' AND date_emprunt + 14 < CURRENT_DATE;
    GET DIAGNOSTICS n = ROW_COUNT;
    RETURN n;
END $$;

/* F2 - Indicateurs du dashboard bibliothécaire / admin (US-DASH-02/03). */
CREATE FUNCTION fn_stats_bibliotheque()
RETURNS TABLE (nb_livres BIGINT, nb_exemplaires BIGINT, emprunts_actifs BIGINT,
               emprunts_en_retard BIGINT, reservations_en_attente BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT (SELECT COUNT(*) FROM livre),
           (SELECT COALESCE(SUM(l.nb_exemplaires_total), 0) FROM livre l),
           (SELECT COUNT(*) FROM emprunt WHERE statut IN ('ACTIVE', 'LATE')),
           (SELECT COUNT(*) FROM emprunt WHERE statut = 'LATE'),
           (SELECT COUNT(*) FROM reservation WHERE statut = 'WAITING');
$$;

/* F3 - Top N des livres les plus empruntés (défaut : 10 sur 12 mois). */
CREATE FUNCTION fn_top_livres(p_top INT DEFAULT 10, p_mois INT DEFAULT 12)
RETURNS TABLE (id_livre BIGINT, titre VARCHAR, auteur VARCHAR, nb_emprunts BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT l.id_livre, l.titre, l.auteur, COUNT(e.id_emprunt)
      FROM livre l
      JOIN emprunt e ON e.id_livre = l.id_livre
     WHERE e.date_emprunt >= CURRENT_DATE - make_interval(months => p_mois)
     GROUP BY l.id_livre
     ORDER BY COUNT(e.id_emprunt) DESC, l.titre
     LIMIT p_top;
$$;

/* F4 - Évolution mensuelle des emprunts (graphique du dashboard). */
CREATE FUNCTION fn_emprunts_par_mois(p_mois INT DEFAULT 12)
RETURNS TABLE (mois DATE, nb_emprunts BIGINT)
LANGUAGE sql STABLE AS $$
    SELECT date_trunc('month', date_emprunt)::date, COUNT(*)
      FROM emprunt
     WHERE date_emprunt >= date_trunc('month', CURRENT_DATE) - make_interval(months => p_mois - 1)
     GROUP BY 1 ORDER BY 1;
$$;

/* F5 - Droit à l'oubli (US-AUTH-03 / RGPD).
   Les emprunts sont conservés (statistiques) mais rattachés à un compte
   anonymisé ; les avis et réservations sont supprimés. */
CREATE FUNCTION fn_anonymiser_utilisateur(p_id_utilisateur BIGINT) RETURNS void LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (SELECT 1 FROM emprunt
                WHERE id_utilisateur = p_id_utilisateur AND statut IN ('ACTIVE', 'LATE')) THEN
        RAISE EXCEPTION 'Suppression impossible : des emprunts sont en cours.';
    END IF;

    DELETE FROM reservation WHERE id_utilisateur = p_id_utilisateur;
    DELETE FROM noter       WHERE id_utilisateur = p_id_utilisateur;

    UPDATE utilisateur
       SET email             = 'deleted-' || id_utilisateur || '@anonymized.invalid',
           mot_de_passe_hash = '!',                          -- aucun hash BCrypt valide
           prenom            = 'Utilisateur',
           nom               = 'supprimé',
           telephone         = NULL,
           pseudonyme        = NULL
     WHERE id_utilisateur = p_id_utilisateur;
END $$;

